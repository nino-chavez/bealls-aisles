#!/usr/bin/env node
// scripts/analytics/derive-referrer-priors.mjs
// Read fingerprinted sessions JSONL, compute per-referrer persona shares
// (excluding "unknown"), emit src/lib/signals/sleepcountry-referrer-priors.ts.
//
// Cohorts with <30 labeled sessions emit `null` and the engine falls back to
// the default category prior. See ADR-011 for the calibration verdict that
// drives this rule.

import { createReadStream } from 'node:fs';
import { createInterface } from 'node:readline';
import { writeFile } from 'node:fs/promises';
import { argv } from 'node:process';

const DEFAULT_INPUT = 'data/sleepcountry-fingerprinted.jsonl';
const DEFAULT_OUTPUT = 'src/lib/signals/sleepcountry-referrer-priors.ts';
const MIN_LABELED = 30;

const REFERRER_BUCKETS = ['internal', 'direct', 'google', 'facebook', 'instagram', 'youtube', 'dormezvous', 'other'];

function parseArgs(args) {
  const opts = { input: DEFAULT_INPUT, output: DEFAULT_OUTPUT };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--input') opts.input = args[++i];
    else if (args[i] === '--output') opts.output = args[++i];
  }
  return opts;
}

async function* readJsonl(path) {
  const stream = createReadStream(path);
  const rl = createInterface({ input: stream, crlfDelay: Infinity });
  for await (const line of rl) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    yield JSON.parse(trimmed);
  }
}

function makeBucketCounts() {
  return Object.fromEntries(
    REFERRER_BUCKETS.map((r) => [r, { researcher: 0, hunter: 0, gatherer: 0, gifter: 0, total: 0 }]),
  );
}

function normalizeBucket(referrer) {
  if (!referrer) return 'direct';
  const r = String(referrer).toLowerCase();
  if (REFERRER_BUCKETS.includes(r)) return r;
  return 'other';
}

function shares(counts) {
  if (counts.total < MIN_LABELED) return null;
  return {
    researcher: counts.researcher / counts.total,
    hunter: counts.hunter / counts.total,
    gatherer: counts.gatherer / counts.total,
    gifter: counts.gifter / counts.total,
  };
}

function fmtProb(p) {
  return p.toFixed(2);
}

function emitTypescript(buckets, counts) {
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/analytics/derive-referrer-priors.mjs');
  lines.push('// Source: data/sleepcountry-fingerprinted.jsonl (gitignored).');
  lines.push('// Re-run after refreshing the fingerprinted data:');
  lines.push('//   node scripts/analytics/fingerprint.mjs --output data/sleepcountry-fingerprinted.jsonl');
  lines.push('//   node scripts/analytics/derive-referrer-priors.mjs');
  lines.push('// See ADR-011 for the calibration verdict; cohorts with <' + MIN_LABELED + ' labeled');
  lines.push('// sessions emit null and the engine falls back to the default category prior.');
  lines.push('');
  lines.push("import type { PersonaProbabilities } from './types';");
  lines.push('');
  lines.push('export const SLEEPCOUNTRY_REFERRER_PRIORS: Record<string, PersonaProbabilities | null> = {');

  for (const bucket of REFERRER_BUCKETS) {
    const c = counts[bucket];
    const s = shares(c);
    const provenance = `// labeled n=${c.total} (researcher=${c.researcher} hunter=${c.hunter} gatherer=${c.gatherer} gifter=${c.gifter})`;
    if (s === null) {
      lines.push(`  ${bucket}: null, ${provenance}, below min ${MIN_LABELED}`);
    } else {
      lines.push(
        `  ${bucket}: { researcher: ${fmtProb(s.researcher)}, hunter: ${fmtProb(s.hunter)}, gatherer: ${fmtProb(s.gatherer)}, gifter: ${fmtProb(s.gifter)} }, ${provenance}`,
      );
    }
  }

  lines.push('};');
  lines.push('');
  lines.push('/**');
  lines.push(' * Bucket a raw referrer domain into one of the SLEEPCOUNTRY_REFERRER_PRIORS keys.');
  lines.push(' * Mirrors scripts/analytics/fingerprint.mjs:bucketReferrer so priors line up with');
  lines.push(' * the offline calibration. Empty / null / "(direct)" → "direct".');
  lines.push(' */');
  lines.push('export function bucketReferrer(domain: string | null | undefined): string {');
  lines.push("  if (!domain || domain === '(direct)') return 'direct';");
  lines.push('  const d = domain.toLowerCase();');
  lines.push("  if (d.includes('facebook')) return 'facebook';");
  lines.push("  if (d.includes('instagram')) return 'instagram';");
  lines.push("  if (d.includes('google')) return 'google';");
  lines.push("  if (d.includes('youtube')) return 'youtube';");
  lines.push("  if (d.includes('dormezvous')) return 'dormezvous';");
  lines.push("  if (d.includes('sleepcountry') || d === 'internal') return 'internal';");
  lines.push("  return 'other';");
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

async function main() {
  const { input, output } = parseArgs(argv.slice(2));

  const counts = makeBucketCounts();
  let totalLabeled = 0;
  let skippedUnknown = 0;

  for await (const row of readJsonl(input)) {
    if (row.persona === 'unknown') {
      skippedUnknown++;
      continue;
    }
    const bucket = normalizeBucket(row.entry?.referrer);
    if (!counts[bucket]) {
      // Defensive: should never happen given normalizeBucket
      counts.other = counts.other ?? { researcher: 0, hunter: 0, gatherer: 0, gifter: 0, total: 0 };
      counts.other[row.persona]++;
      counts.other.total++;
      continue;
    }
    counts[bucket][row.persona]++;
    counts[bucket].total++;
    totalLabeled++;
  }

  const ts = emitTypescript(REFERRER_BUCKETS, counts);
  await writeFile(output, ts, 'utf8');

  console.error(`Wrote ${output}`);
  console.error(`Labeled sessions: ${totalLabeled} (skipped ${skippedUnknown} unknown)`);
  for (const bucket of REFERRER_BUCKETS) {
    const c = counts[bucket];
    const s = shares(c);
    const status = s === null ? `(below ${MIN_LABELED}, NULL)` : '';
    console.error(`  ${bucket.padEnd(11)} n=${String(c.total).padStart(5)} ${status}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
